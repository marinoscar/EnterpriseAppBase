#!/usr/bin/env node
// =============================================================================
// Generates packages/platform-web/src/timezone/headless/map-data.ts
// =============================================================================
//
// The time zone picker draws a dot-matrix world map and pins each IANA zone at
// its principal city. Both are bundled, never fetched: a packaged page loads no
// remote asset (KVox Desktop keeps every byte on the device, ADR-0004).
//
//   - Land mask: Natural Earth 1:50m countries (public domain) as published by the
//     `world-atlas` package (ISC), rasterised to a 1.5 degree grid and encoded
//     one hex string per row.
//   - Zone pins: tzdata `zone.tab` (public domain): every zone with its
//     country code and the coordinates of its principal city.
//
// Run it only when the tzdata or the grid changes; the output is checked in.
//
//   mkdir /tmp/tzgen && cd /tmp/tzgen && npm i world-atlas@2.0.2 topojson-client@3.1.0 d3-geo@3.1.1
//   node <repo>/packages/platform-web/scripts/generate-timezone-map.mjs \
//     /tmp/tzgen/node_modules/world-atlas/countries-50m.json /usr/share/zoneinfo/zone.tab
//
// (topojson-client and d3-geo are resolved next to the topology file.)
// =============================================================================

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const [landPath, zoneTabPath] = process.argv.slice(2);
if (!landPath || !zoneTabPath) {
  console.error('usage: generate-timezone-map.mjs <countries-50m.json> <zone.tab>');
  process.exit(1);
}

const require = createRequire(resolve(landPath));
const { feature } = require('topojson-client');
const { geoBounds, geoContains } = require('d3-geo');

// The grid: 1.5 degree cells, 84N to 58S (Antarctica carries no zone a person picks).
const STEP = 1.5;
const NORTH = 84;
const SOUTH = -58;
const COLS = Math.round(360 / STEP);
const ROWS = Math.round((NORTH - SOUTH) / STEP);

const topology = JSON.parse(readFileSync(landPath, 'utf8'));
const objectName = topology.objects.countries ? 'countries' : 'land';
const collection = feature(topology, topology.objects[objectName]);
// Spherical containment (d3-geo), so rings that cross the antimeridian (Russia,
// Fiji) are read as the sphere draws them; a planar ray cast paints bands.
const shapes = (collection.features ?? [collection]).map((shape) => ({ shape, bounds: geoBounds(shape) }));

function inBounds([[west, south], [east, north]], lon, lat) {
  if (lat < south || lat > north) return false;
  // west > east: the box crosses the antimeridian.
  return west <= east ? lon >= west && lon <= east : lon >= west || lon <= east;
}

function isLand(lon, lat) {
  return shapes.some(({ shape, bounds }) => inBounds(bounds, lon, lat) && geoContains(shape, [lon, lat]));
}

const rows = [];
let landCells = 0;
for (let r = 0; r < ROWS; r += 1) {
  const bits = [];
  for (let c = 0; c < COLS; c += 1) {
    // A cell is land when any of five samples (centre and four inner corners) is:
    // a small island still earns its dot.
    const lat0 = NORTH - (r + 0.5) * STEP;
    const lon0 = -180 + (c + 0.5) * STEP;
    const q = STEP / 4;
    const hit = [[0, 0], [-q, -q], [q, -q], [-q, q], [q, q]].some(([dx, dy]) => isLand(lon0 + dx, lat0 + dy));
    if (hit) landCells += 1;
    bits.push(hit ? 1 : 0);
  }
  let hex = '';
  for (let i = 0; i < bits.length; i += 4) hex += ((bits[i] << 3) | (bits[i + 1] << 2) | (bits[i + 2] << 1) | bits[i + 3]).toString(16);
  rows.push(hex);
}

// ISO 6709: +DDMM+DDDMM or +DDMMSS+DDDMMSS.
function parseIso6709(value) {
  const match = /^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$/.exec(value);
  if (!match) throw new Error(`bad coordinates ${value}`);
  const [, ls, ld, lm, lsec = '0', os, od, om, osec = '0'] = match;
  const lat = (ls === '-' ? -1 : 1) * (Number(ld) + Number(lm) / 60 + Number(lsec) / 3600);
  const lon = (os === '-' ? -1 : 1) * (Number(od) + Number(om) / 60 + Number(osec) / 3600);
  return [Math.round(lat * 100) / 100, Math.round(lon * 100) / 100];
}

const zones = readFileSync(zoneTabPath, 'utf8')
  .split('\n')
  .filter((line) => line && !line.startsWith('#'))
  .map((line) => {
    const [country, coordinates, id] = line.split('\t');
    const [lat, lon] = parseIso6709(coordinates);
    return [id, country, lat, lon];
  })
  .sort((a, b) => a[0].localeCompare(b[0]));

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../src/timezone/headless/map-data.ts');
const body = `// GENERATED by packages/platform-web/scripts/generate-timezone-map.mjs; never hand-edit.
// Land: Natural Earth 1:50m countries (public domain) via world-atlas (ISC). Zones: tzdata zone.tab (public domain).

/** Degrees per grid cell of {@link LAND_ROWS}. */
export const LAND_STEP = ${STEP};
/** Latitude of the top edge of the first row. */
export const LAND_NORTH = ${NORTH};
/** Latitude of the bottom edge of the last row. */
export const LAND_SOUTH = ${SOUTH};
/** Cells per row, from 180W eastwards. */
export const LAND_COLS = ${COLS};

/** One hex string per row, north to south; bit set = land (${landCells} cells). */
export const LAND_ROWS: readonly string[] = [
${rows.map((row) => `  '${row}',`).join('\n')}
];

/** \`[IANA id, ISO 3166 country, latitude, longitude]\` of each zone's principal city (${zones.length} zones). */
export const ZONE_PINS: ReadonlyArray<readonly [string, string, number, number]> = [
${zones.map(([id, country, lat, lon]) => `  ['${id}', '${country}', ${lat}, ${lon}],`).join('\n')}
];
`;
writeFileSync(out, body);
console.log(`wrote ${out}: ${ROWS}x${COLS} grid, ${landCells} land cells, ${zones.length} zones`);
